def build_inventory_data(dim, sales):
    """根据销售需求模拟补货，生成采购单、库存与库存流水。"""
    product_info = dim["product_info"]
    wh_ids = list(range(1, len(WAREHOUSES) + 1))
    order_meta = sales["order_meta"]
    shipped_statuses = {"已完成", "已发货"}

    # 销售出库需求与退货入库需求
    demand = defaultdict(list)
    sales_out = []   # (item_id, wh, pid, qty, date, order_no)
    for it in sales["item_rows"]:
        oid = it[1]
        meta = order_meta[oid]
        if meta["status"] not in shipped_statuses:
            continue
        wh = meta["warehouse_id"]
        pid = it[2]
        qty = it[3]
        demand[(wh, pid)].append((meta["date"], -qty))
        sales_out.append((it[0], wh, pid, qty, meta["date"], meta["order_no"]))

    ret_by_id = {r[0]: r for r in sales["return_rows"]}
    returns_in = []
    for row in sales["return_item_rows"]:
        ret_row = ret_by_id[row[1]]
        if ret_row[6] != "已完成":
            continue
        demand[(ret_row[4], row[2])].append((ret_row[5], row[3]))
        returns_in.append((row[0], ret_row[4], row[2], row[3], ret_row[5], ret_row[1]))

    # 期初库存与安全库存（按平均日需求）
    initial = {}
    safety = {}
    avg_daily = {}
    for key, events in demand.items():
        dates = sorted({d for d, _ in events})
        span = max(1, (dates[-1] - dates[0]).days + 1)
        total_out = -sum(delta for _, delta in events if delta < 0)
        ad = total_out / span
        avg_daily[key] = ad
        initial[key] = max(1, int(ad * rng.uniform(15, 30)))
        safety[key] = max(1, int(ad * rng.uniform(5, 10)))

    # 模拟补货：按实际收货量入账，保证库存不低于安全库存
    receipts = []  # (order_date, wh, pid, ordered_qty, received_qty, received_date)
    final_stock = {}
    for key, events in demand.items():
        stock = initial[key]
        ad = avg_daily[key]
        for ev_date, delta in sorted(events):
            while stock + delta < safety[key]:
                rdate = max(START_DATE, ev_date - timedelta(days=rng.randint(2, 8)))
                rq = max(1, int(ad * rng.uniform(10, 22)))
                if rng.random() < 0.10:
                    received = max(1, int(round(rq * rng.uniform(0.5, 0.9))))
                else:
                    received = rq
                rec_date = min(ev_date, rdate + timedelta(days=rng.randint(1, 2)))
                receipts.append((rdate, key[0], key[1], rq, received, rec_date))
                stock += received
            stock += delta
        final_stock[key] = stock

    # 按 (日期, 仓库, 供应商) 归组生成采购单
    po_groups = defaultdict(list)
    for rdate, wh, pid, ordered, received, rec_date in receipts:
        sup = product_info[pid]["supplier_id"]
        po_groups[(rdate, wh, sup)].append((pid, ordered, received, rec_date))

    po_rows = []
    poi_rows = []
    poi_id = 1
    po_seq = defaultdict(int)
    po_id = 1
    for key in sorted(po_groups, key=lambda k: (k[0], k[1], k[2])):
        rdate, wh, sup = key
        items = po_groups[key]
        po_seq[rdate] += 1
        po_no = f"PO{rdate:%Y%m%d}{po_seq[rdate]:04d}"
        partial = any(received < ordered for _, ordered, received, _ in items)
        po_status = "部分收货" if partial else "已完成"
        expected = rdate + timedelta(days=rng.randint(3, 7))
        total_amount = 0.0
        rec_dates = []
        cold = False
        for pid, ordered, received, rec_date in items:
            info = product_info[pid]
            uc = cost_at(info, rdate)
            amount = round(uc * ordered, 2)
            total_amount += amount
            cold = cold or info["is_cold_chain"]
            if received > 0 and rec_date is not None:
                rec_dates.append(rec_date)
            poi_rows.append((poi_id, po_id, pid, ordered, money(uc), money(amount),
                             received, rec_date))
            poi_id += 1
        header_rec_date = max(rec_dates) if rec_dates else None
        delivery_type = "冷链运输" if cold else "常温运输"
        po_rows.append((po_id, po_no, sup, wh, rdate, expected, header_rec_date,
                        po_status, money(total_amount), delivery_type, "",
                        rand_time(rdate)))
        po_id += 1

    po_by_id = {r[0]: r for r in po_rows}

    # 追加在途采购单（未收货，不影响库存与流水）
    open_pids = list(product_info.keys())
    for _ in range(90):
        rdate = END_DATE - timedelta(days=rng.randint(0, 30))
        wh = rng.choice(wh_ids)
        pid = rng.choice(open_pids)
        info = product_info[pid]
        sup = info["supplier_id"]
        ordered = max(1, int(avg_daily.get((wh, pid), 1) * rng.uniform(8, 18)))
        po_seq[rdate] += 1
        po_no = f"PO{rdate:%Y%m%d}{po_seq[rdate]:04d}"
        uc = cost_at(info, rdate)
        amount = round(uc * ordered, 2)
        po_rows.append((po_id, po_no, sup, wh, rdate, rdate + timedelta(days=7), None,
                        "待收货", money(amount),
                        "冷链运输" if info["is_cold_chain"] else "常温运输",
                        "计划备货", rand_time(rdate)))
        poi_rows.append((poi_id, po_id, pid, ordered, money(uc), money(amount), 0, None))
        poi_id += 1
        po_id += 1

    # ---- 库存流水 ----
    dept_id_by_code = dim["dept_id_by_code"]
    wh_staff = [
        r[0] for r in dim["rows_emp"]
        if r[6] == dept_id_by_code["D003"] and r[10] == "在职"
        and r[7] in ("仓管员", "仓库主管", "冷链管理员")
    ]
    movements = []
    for (wh, pid), qty in initial.items():
        if qty > 0:
            movements.append((wh, pid, "期初入库", qty, START_DATE, None, None,
                              rng.choice(wh_staff), "期初建账", f"{START_DATE} 08:00:00"))

    for poi_row in poi_rows:
        if poi_row[6] > 0:
            po_row = po_by_id[poi_row[1]]
            movements.append((po_row[3], poi_row[2], "采购入库", poi_row[6],
                              poi_row[7], "purchase_order_item", poi_row[0],
                              rng.choice(wh_staff), f"采购单 {po_row[1]}",
                              rand_time(poi_row[7])))

    for item_id, wh, pid, qty, d, order_no in sales_out:
        movements.append((wh, pid, "销售出库", -qty, d, "sales_order_item", item_id,
                          rng.choice(wh_staff), f"订单 {order_no}", rand_time(d)))

    for rit_id, wh, pid, qty, d, ret_no in returns_in:
        movements.append((wh, pid, "退货入库", qty, d, "sales_return_item", rit_id,
                          rng.choice(wh_staff), f"退货单 {ret_no}", rand_time(d)))

    type_rank = {"期初入库": 0, "采购入库": 1, "退货入库": 2, "销售出库": 3}
    movements.sort(key=lambda m: (m[4], type_rank[m[2]], m[0], m[1]))
    mv_rows = []
    for idx, m in enumerate(movements, start=1):
        mv_rows.append((idx, m[0], m[1], m[2], m[3], m[4], m[5], m[6], m[7], m[8], m[9]))

    # 库存表
    inv_rows = []
    inv_id = 1
    for (wh, pid), qty in final_stock.items():
        inv_rows.append((inv_id, wh, pid, qty, safety[(wh, pid)],
                         f"{END_DATE} 23:59:59"))
        inv_id += 1

    print(f"[generate] 采购与库存构建完成：{len(po_rows):,} 采购单 / "
          f"{len(poi_rows):,} 采购明细 / {len(inv_rows):,} 库存记录 / "
          f"{len(mv_rows):,} 库存流水")
    return {
        "po_rows": po_rows,
        "poi_rows": poi_rows,
        "inv_rows": inv_rows,
        "mv_rows": mv_rows,
    }


