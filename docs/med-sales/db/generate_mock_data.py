def build_price_events(cat: str, base_price: float, base_cost: float, listed: date):
    """生成价格调整事件，返回（最新售价, 售价事件, 成本事件）。"""
    lo, hi = PRICE_DRIFT[cat]
    price_events = []
    cost_events = []
    cur_price = base_price
    cur_cost = base_cost
    d = listed + timedelta(days=rng.randint(30, 120))
    n_events = rng.randint(2, 5)
    for _ in range(n_events):
        if d > END_DATE:
            break
        drift = rng.uniform(lo, hi) * rng.uniform(0.4, 1.0)
        new_price = round(cur_price * (1 + drift), 2)
        if new_price <= 0:
            new_price = round(cur_price * 0.5, 2)
        margin = CATEGORY_MARGIN[cat]
        new_cost = round(new_price * (1 - margin) * rng.uniform(0.995, 1.005), 2)
        price_events.append((d, new_price))
        cost_events.append((d, new_cost))
        cur_price = new_price
        cur_cost = new_cost
        d += timedelta(days=rng.randint(120, 400))
    return cur_price, price_events, cost_events


def price_at(info: dict, d: date) -> float:
    events = info["price_events"]
    if not events:
        return info["base_price"]
    idx = bisect_right(info["price_dates"], d)
    return events[idx - 1][1] if idx > 0 else info["base_price"]


def cost_at(info: dict, d: date) -> float:
    events = info["cost_events"]
    if not events:
        return info["base_cost"]
    idx = bisect_right(info["cost_dates"], d)
    return events[idx - 1][1] if idx > 0 else info["base_cost"]


