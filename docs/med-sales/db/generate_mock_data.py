def build_order_pools(dim):
    """构建下单所需的查找结构：客户池、销售代表、商品池、分类偏好。"""
    customers = dim["customers"]
    customers_by_type = defaultdict(list)
    for c in customers:
        if c["status"] == "正常":
            customers_by_type[c["type"]].append(c)
    for ctype in customers_by_type:
        customers_by_type[ctype].sort(key=lambda c: c["id"])

    # 商品池：按分类聚合（含权重累积），过滤停用/未上市
    cat_products = defaultdict(list)
    for info in dim["product_info"].values():
        if not info["active"]:
            continue
        cat_products[info["category"]].append(info)
    for cat in cat_products:
        cat_products[cat].sort(key=lambda x: x["pid"])

    # 销售代表：按区域聚合（在职销售岗）
    dept_region = {"D101": "EST", "D102": "SCT", "D103": "NCT", "D104": "CCT",
                   "D105": "HEN", "D106": "SDN", "D107": "SWT", "D108": "NWT",
                   "D109": "NET"}
    dept_id_to_code = {v: k for k, v in dim["dept_id_by_code"].items()}
    reps_by_region = defaultdict(list)
    rep_weight = {}
    for row in dim["rows_emp"]:
        if row[10] != "在职":
            continue
        dept_code = dept_id_to_code[row[6]]
        if dept_code not in dept_region:
            continue
        if row[7] not in ("区域销售总监", "高级销售代表", "销售代表", "销售助理",
                          "大客户经理", "销售总监", "销售运营经理", "商务专员"):
            continue
        region = dept_region[dept_code]
        reps_by_region[region].append(row[0])
        rep_weight[row[0]] = 1.0

    # 分类偏好累积权重
    affinity_cum = {}
    for ctype, aff in TYPE_AFFINITY.items():
        cats = [c for c, w in aff.items() if w > 0]
        cum = []
        acc = 0.0
        for c in cats:
            acc += aff[c]
            cum.append(acc)
        affinity_cum[ctype] = (cats, cum, acc)

    return {
        "customers_by_type": customers_by_type,
        "cat_products": cat_products,
        "reps_by_region": reps_by_region,
        "rep_weight": rep_weight,
        "affinity_cum": affinity_cum,
    }


