def make_order(pools, ctype, day):
    """生成一个订单（未缩放）。"""
    custs = pools["customers_by_type"][ctype]
    eligible = [c for c in custs if c["next_date"] <= day]
    if eligible:
        cum = []
        acc = 0.0
        for c in eligible:
            acc += c["weight"]
            cum.append(acc)
        cust = eligible[weighted_pick(cum, acc)]
    else:
        cust = min(custs, key=lambda c: c["next_date"])
    gap_lo, gap_hi = cust["gap"]
    cust["next_date"] = day + timedelta(days=rng.randint(gap_lo, gap_hi))

    region = cust["region"]
    reps = pools["reps_by_region"][region]
    rep_w = pools["rep_weight"]
    cum = []
    acc = 0.0
    for rid in reps:
        acc += rep_w[rid]
        cum.append(acc)
    emp_id = reps[weighted_pick(cum, acc)]

    cats, cumc, totalc = pools["affinity_cum"][ctype]
    cat = cats[weighted_pick(cumc, totalc)]

    items, cum_p, tot_p = pools["cat_cum"][cat]
    desired = cust["avg_order"] * rng.uniform(0.6, 1.4)
    lines = []
    amount = 0.0
    attempts = 0
    while amount < desired and len(lines) < MAX_LINES and attempts < 60:
        attempts += 1
        info = items[weighted_pick(cum_p, tot_p)]
        if info["listed_date"] > day:
            continue
        lo, hi = CATEGORY_QTY[cat]
        qty = equip_qty() if cat == "CAT-EQUIP" else log_uniform(lo, hi)
        up = price_at(info, day)
        uc = cost_at(info, day)
        rate = 0.0
        if rng.random() < cust["disc_prob"]:
            rate = cust["disc_rate"]
        disc = round(up * qty * rate, 2)
        amt = round(up * qty - disc, 2)
        if amt <= 0:
            rate = 0.0
            disc = 0.0
            amt = round(up * qty, 2)
        if lines and amount + amt > desired * 1.35:
            break
        lines.append([info["pid"], qty, up, uc, rate, disc, amt,
                      info["is_cold_chain"], cat])
        amount += amt

    if not lines:
        return None

    # 按期望金额缩放（订单级）
    factor = desired / amount if amount else 1.0
    for ln in lines:
        v = ln[1] * factor
        base = int(v)
        frac = v - base
        nq = max(1, base + (1 if rng.random() < frac else 0))
        ln[1] = nq
        up = ln[2]
        disc = round(up * nq * ln[4], 2)
        amt = round(up * nq - disc, 2)
        if amt < round(ln[3] * nq, 2):  # 保证毛利为正
            ln[4] = 0.0
            disc = 0.0
            amt = round(up * nq, 2)
        ln[5] = disc
        ln[6] = amt

    cancelled = rng.random() < 0.05
    rep_w[emp_id] += desired / 1e7
    return {
        "date": day,
        "ctype": ctype,
        "customer": cust,
        "region": region,
        "warehouse_id": REGION_INFO[region]["wh"],
        "employee_id": emp_id,
        "lines": lines,
        "cancelled": cancelled,
    }


def scale_year(orders, year):
    """按年度/分类目标缩放订单数量，使各分类销售额贴合目标。"""
    gross = defaultdict(float)
    for od in orders:
        if od["cancelled"]:
            continue
        for ln in od["lines"]:
            gross[ln[8]] += ln[6]
    factors = {}
    target = year_target(year, START_DATE, END_DATE)
    for cat, share in CATEGORY_SHARE.items():
        want = target * share
        factors[cat] = want / gross[cat] if gross.get(cat, 0) > 0 else 1.0
    for od in orders:
        if od["cancelled"]:
            continue
        for ln in od["lines"]:
            f = factors[ln[8]]
            v = ln[1] * f
            base = int(v)
            frac = v - base
            nq = max(1, base + (1 if rng.random() < frac else 0))
            ln[1] = nq
            up = ln[2]
            disc = round(up * nq * ln[4], 2)
            amt = round(up * nq - disc, 2)
            if amt < round(ln[3] * nq, 2):
                ln[4] = 0.0
                disc = 0.0
                amt = round(up * nq, 2)
            ln[5] = disc
            ln[6] = amt


def finalize_order(od, order_no):
    """按订单行生成最终金额与状态/付款信息。"""
    cust = od["customer"]
    subtotal = 0.0
    row_disc = 0.0
    cost_total = 0.0
    total_qty = 0
    cold = False
    for ln in od["lines"]:
        subtotal += ln[2] * ln[1]
        row_disc += ln[5]
        cost_total += ln[3] * ln[1]
        total_qty += ln[1]
        cold = cold or ln[7]
    rebate = 0.0
    if rng.random() < 0.05:
        cap = max(0.0, round(subtotal - row_disc, 2) * 0.003)
        rebate = round(rng.uniform(100, min(10000, cap)), 2) if cap > 0 else 0.0
    total = round(subtotal - row_disc - rebate, 2)
    if total < 0:
        total = round(subtotal - row_disc, 2)
        rebate = 0.0
    discount_amount = round(row_disc + rebate, 2)

    ctype = cust["type"]
    credit_days = cust["credit_days"]
    settlement = CREDIT_DAYS_TO_METHOD[credit_days]
    if credit_days == 0:
        pay_date = od["date"] + timedelta(days=rng.randint(0, 2))
    else:
        pay_date = od["date"] + timedelta(days=credit_days) + timedelta(days=rng.randint(-5, 10))
        if pay_date < od["date"] + timedelta(days=1):
            pay_date = od["date"] + timedelta(days=1)
    paid = pay_date <= END_DATE

    if cold:
        delivery_type = "冷链运输"
    elif ctype in ("单体药房", "其他机构") and total < 30000:
        delivery_type = "快递配送"
    else:
        delivery_type = "常温运输"

    if ctype in ("三级医院", "二级医院", "疾控中心", "连锁药房", "经销商", "民营医院"):
        invoice_type = "增值税专用发票" if rng.random() < 0.9 else "增值税普通发票"
    else:
        invoice_type = rng.choices(
            ["增值税普通发票", "不开发票", "增值税专用发票"], weights=[60, 20, 20])[0]

    if paid:
        status = "已完成"
        paid_amount = total
    else:
        status = "已发货" if rng.random() < 0.85 else "待付款"
        paid_amount = 0.0

    delivery_date = None
    if status in ("已完成", "已发货"):
        delivery_date = min(END_DATE, od["date"] + timedelta(days=rng.randint(0, 3)))

    item_count = len(od["lines"])
    remark = rng.choice(ORDER_REMARKS)
    created = rand_time(od["date"])
    row = (
        None, order_no, cust["id"], od["employee_id"], od["warehouse_id"],
        od["date"], status, item_count, total_qty, money(subtotal),
        money(discount_amount), money(total), money(paid_amount), money(cost_total),
        cust["address"], invoice_type, settlement, delivery_type, delivery_date,
        remark, created,
    )
    pay_info = None
    if paid:
        method = rng.choices(
            [m for m, _ in PAY_METHODS[ctype]],
            weights=[w for _, w in PAY_METHODS[ctype]],
        )[0]
        pay_info = (cust["id"], pay_date, total, method, order_no)
    return row, pay_info


def build_sales_data(dim):
    """生成全部销售订单、明细、付款与退货。"""
    pools = build_order_pools(dim)
    pools["cat_cum"] = {}
    for cat, items in pools["cat_products"].items():
        cum = []
        acc = 0.0
        for it in items:
            acc += it["weight"]
            cum.append(acc)
        pools["cat_cum"][cat] = (items, cum, acc)

    total_weight = sum(p["weight"] for p in CUSTOMER_TYPE_PLAN.values())
    order_rows = []
    item_rows = []
    payment_rows = []
    order_meta = {}
    order_items_map = {}
    oid = 1
    item_id = 1
    pay_id = 1

    for year in target_years(START_DATE, END_DATE):
        start = max(START_DATE, date(year, 1, 1))
        end = min(END_DATE, date(year, 12, 31))
        days = list(iter_days(start, end))
        day_ws = []
        for d in days:
            w = MONTH_WEIGHT[d.month] * DOW_WEIGHT[d.weekday()]
            if (d + timedelta(days=5)).month != d.month:
                w *= 1.12
            elif d.day <= 5:
                w *= 0.90
            day_ws.append(w)
        sum_w = sum(day_ws)

        type_orders_year = {}
        for t, p in CUSTOMER_TYPE_PLAN.items():
            share = p["weight"] / total_weight
            type_orders_year[t] = year_target(year, START_DATE, END_DATE) * share / p["avg_order"]

        orders_year = []
        so_seq = defaultdict(int)
        for d, w in zip(days, day_ws):
            for t, p in CUSTOMER_TYPE_PLAN.items():
                expected = type_orders_year[t] * w / sum_w
                n = max(0, int(expected * rng.uniform(0.75, 1.25) + 0.5))
                for _ in range(n):
                    od = make_order(pools, t, d)
                    if od is None:
                        continue
                    so_seq[d] += 1
                    od["order_no"] = f"SO{d:%Y%m%d}{so_seq[d]:04d}"
                    orders_year.append(od)

        scale_year(orders_year, year)

        for od in orders_year:
            order_no = od["order_no"]
            cust = od["customer"]
            if od["cancelled"]:
                status = "已取消"
                order_total = 0.0
                subtotal = sum(ln[2] * ln[1] for ln in od["lines"])
                cost_total = sum(ln[3] * ln[1] for ln in od["lines"])
                total_qty = sum(ln[1] for ln in od["lines"])
                order_rows.append((
                    oid, order_no, cust["id"], od["employee_id"], od["warehouse_id"],
                    od["date"], status, len(od["lines"]), total_qty, money(subtotal),
                    "0.00", "0.00", "0.00", money(cost_total), cust["address"],
                    "不开发票", CREDIT_DAYS_TO_METHOD[cust["credit_days"]],
                    "常温运输", None, "已取消订单", rand_time(od["date"]),
                ))
            else:
                row, pay_info = finalize_order(od, order_no)
                status = row[6]
                order_total = float(row[11])
                order_rows.append((oid,) + tuple(row[1:]))
                if pay_info:
                    payment_rows.append((pay_id, oid, pay_info[0], pay_info[1],
                                         money(pay_info[2]), pay_info[3], "成功",
                                         pay_info[4], rand_time(pay_info[1])))
                    pay_id += 1
            order_meta[oid] = {
                "status": status,
                "date": od["date"],
                "warehouse_id": od["warehouse_id"],
                "customer_id": cust["id"],
                "order_no": order_no,
                "total_amount": order_total,
            }
            order_items_map[oid] = od["lines"]
            for ln in od["lines"]:
                item_rows.append((
                    item_id, oid, ln[0], ln[1], money(ln[2]), money(ln[3]),
                    f"{ln[4]:.4f}", money(ln[5]), money(ln[6]),
                ))
                item_id += 1
            oid += 1
        print(f"[generate] {year} 年销售构建完成：订单 {len(orders_year):,} 笔")

    # ---- 退货 ----
    return_rows = []
    return_item_rows = []
    ret_id = 1
    rit_id = 1
    rt_seq = defaultdict(int)
    eligible = [
        (oid, meta) for oid, meta in order_meta.items()
        if meta["status"] in ("已完成", "已发货")
        and meta["date"] <= END_DATE - timedelta(days=5)
    ]
    for oid, meta in eligible:
        if rng.random() >= 0.025:
            continue
        lines = [ln for ln in order_items_map[oid] if ln[1] > 0]
        if not lines:
            continue
        n_ret = rng.randint(1, min(2, len(lines)))
        chosen = rng.sample(lines, n_ret)
        ret_date = min(END_DATE, meta["date"] + timedelta(days=rng.randint(5, 20)))
        rt_seq[ret_date] += 1
        return_no = f"RT{ret_date:%Y%m%d}{rt_seq[ret_date]:04d}"
        reasons = []
        ret_total = 0.0
        candidate = []
        for ln in chosen:
            qty = rng.randint(1, ln[1])
            amount = round(ln[2] * qty, 2)
            reason = rng.choice(RETURN_REASONS)
            reasons.append(reason)
            candidate.append((ln[0], qty, ln[2], amount, reason))
            ret_total += amount
        if ret_total > meta["total_amount"]:
            continue  # 退款金额不超过订单应付金额
        for pid, qty, up, amount, reason in candidate:
            return_item_rows.append((rit_id, ret_id, pid, qty, money(up),
                                     money(amount), reason))
            rit_id += 1
        status = "已完成" if rng.random() < 0.88 else "待处理"
        order_reason = "部分商品退货" if len(reasons) > 1 else reasons[0]
        return_rows.append((ret_id, return_no, oid, meta["customer_id"],
                            meta["warehouse_id"], ret_date, status, order_reason,
                            money(ret_total), f"原订单 {meta['order_no']}",
                            rand_time(ret_date)))
        ret_id += 1

    print(f"[generate] 销售数据构建完成：{len(order_rows):,} 订单 / "
          f"{len(item_rows):,} 明细 / {len(payment_rows):,} 付款 / "
          f"{len(return_rows):,} 退货单 / {len(return_item_rows):,} 退货明细")
    return {
        "order_rows": order_rows,
        "item_rows": item_rows,
        "payment_rows": payment_rows,
        "return_rows": return_rows,
        "return_item_rows": return_item_rows,
        "order_meta": order_meta,
        "order_items_map": order_items_map,
    }


