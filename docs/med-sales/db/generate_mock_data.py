def parse_args(argv=None):
    parser = argparse.ArgumentParser(description="生成 medsalesdb 演示 mock 数据")
    parser.add_argument("--seed", type=int, default=None,
                        help=f"随机种子，默认 {SEED}（见 mock_params.py）")
    parser.add_argument("--start-date", default=None,
                        help=f"数据起始日期 YYYY-MM-DD，默认 {START_DATE}")
    parser.add_argument("--end-date", default=None,
                        help=f"数据结束日期 YYYY-MM-DD，默认 {END_DATE}")
    return parser.parse_args(argv)


def apply_args(args) -> None:
    """把命令行参数写回模块级参数（生成脚本内部统一读模块级变量）。"""
    global SEED, START_DATE, END_DATE
    if args.seed is not None:
        SEED = args.seed
    if args.start_date is not None:
        START_DATE = date.fromisoformat(args.start_date)
    if args.end_date is not None:
        END_DATE = date.fromisoformat(args.end_date)
    if START_DATE > END_DATE:
        raise SystemExit(f"起始日期 {START_DATE} 不能晚于结束日期 {END_DATE}")
    rng.seed(SEED)


def check_scale() -> None:
    """校验部门/客户计划表与 mock_params.py 中的规模目标一致。"""
    plan_employees = sum(cnt for _, positions in DEPT_PLAN for _, cnt in positions)
    if plan_employees != EMPLOYEE_COUNT:
        raise SystemExit(
            f"DEPT_PLAN 合计 {plan_employees} 人，与 mock_params.EMPLOYEE_COUNT="
            f"{EMPLOYEE_COUNT} 不一致，请同步修改"
        )
    plan_customers = sum(p["count"] for p in CUSTOMER_TYPE_PLAN.values())
    if plan_customers != CUSTOMER_COUNT:
        raise SystemExit(
            f"CUSTOMER_TYPE_PLAN 合计 {plan_customers} 家，与 mock_params.CUSTOMER_COUNT="
            f"{CUSTOMER_COUNT} 不一致，请同步修改"
        )


